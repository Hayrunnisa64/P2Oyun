    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String tahmin = jTextField2.getText().trim();
        
        if (tahmin.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Lütfen bir kelime girin!");
        return;
    }
    
    if (tahmin.toUpperCase().equals(seciliKelime.toUpperCase())) {
        timer.stop();
        oyunuKaydet("KAZANDI");
        jButton1.setEnabled(false);
        jButton2.setEnabled(false);

        for (int i = 0; i < harfPaneli.getComponentCount(); i++) {
            JLabel siradakiLabel = (JLabel) harfPaneli.getComponent(i);
            siradakiLabel.setText(String.valueOf(seciliKelime.charAt(i)));
        }
        JOptionPane.showMessageDialog(this, "Tebrikler! Kelimeyi buldunuz");
    } else {
        yanlisTahmin++;
        resimGoster();
        if (yanlisTahmin >= 11) {
            timer.stop();
            oyunuKaydet("KAYBETTİ");
            jButton1.setEnabled(false);
            jButton2.setEnabled(false);
            
            for (int i = 0; i < harfPaneli.getComponentCount(); i++) {
            JLabel siradakiLabel = (JLabel) harfPaneli.getComponent(i);
            siradakiLabel.setText(String.valueOf(seciliKelime.charAt(i)));
         }
        JOptionPane.showMessageDialog(this, "Oyunu kaybettiniz! Kelime: " + seciliKelime);
    } else {
        JOptionPane.showMessageDialog(this, "Kelimeyi yanlış tahmin ettiniz! Kalan hakkınız: " + (11 - yanlisTahmin));
    }
    }
    
    jTextField2.setText("");
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String tahmin = jTextField1.getText().trim();
        
         if (tahmin.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Lütfen bir harf girin!");
        return;
    }
    
    if (tahmin.length() != 1) {
        JOptionPane.showMessageDialog(this, "Lütfen tek harf girin!");
        return;
    }
    
        boolean bulundu = false;
    
    for (int i = 0; i < harfPaneli.getComponentCount(); i++) {
        JLabel siradakiLabel = (JLabel) harfPaneli.getComponent(i);
        
        if (tahmin.toUpperCase().equals(String.valueOf(seciliKelime.toUpperCase().charAt(i)))) {
            siradakiLabel.setText(tahmin.toUpperCase());
            bulundu = true;
        }
    }
    
    if (bulundu == true) {
        JOptionPane.showMessageDialog(this, "Harf bulundu!");
        
        boolean hepsiAcildi = true;
    for (int i = 0; i < harfPaneli.getComponentCount(); i++) {
        JLabel siradakiLabel = (JLabel) harfPaneli.getComponent(i);
        if (siradakiLabel.getText().equals("*")) {
            hepsiAcildi = false;
            break;
        }
    }
    
    if (hepsiAcildi) {
        timer.stop();
        oyunuKaydet("KAZANDI");
        jButton1.setEnabled(false);
        jButton2.setEnabled(false);
        JOptionPane.showMessageDialog(this, "Tebrikler! Kelimeyi buldunuz!");
    }
    
    } else {
        yanlisTahmin++;
        resimGoster();
        if (yanlisTahmin >= 11) {
            timer.stop();
            oyunuKaydet("KAYBETTİ");
            jButton1.setEnabled(false);
            jButton2.setEnabled(false);
            
             for (int i = 0; i < harfPaneli.getComponentCount(); i++) {
            JLabel siradakiLabel = (JLabel) harfPaneli.getComponent(i);
            siradakiLabel.setText(String.valueOf(seciliKelime.charAt(i)));
         }
            JOptionPane.showMessageDialog(this, "Oyunu kaybettiniz! Kelime: " + seciliKelime);
        } else {
            JOptionPane.showMessageDialog(this, "Harf yok! Kalan hakkınız: " + (11 - yanlisTahmin));
        }
    }
    
    jTextField1.setText("");
    }//GEN-LAST:event_jButton1ActionPerformed

