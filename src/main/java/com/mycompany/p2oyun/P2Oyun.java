    private void oyunuBaslat() {
        jButton1.setEnabled(true);
        jButton2.setEnabled(true);
        jTabbedPane2.setEnabledAt(2, true);
        resimIndex = 1;
        jLabel4.setIcon(null);
    try {
         List<String> liste = Files.readAllLines(new File(kelimelerDosyaAdi).toPath(), Charset.defaultCharset());
        
        Random random = new Random();
        seciliKelime = liste.get(random.nextInt(liste.size())).toUpperCase().trim();
        
        int harfSayisi = seciliKelime.length();
        
        harfPaneli.removeAll();
        harfPaneli.setLayout(new FlowLayout(java.awt.FlowLayout.LEFT, 5, 5));
        
        for (int i = 0; i < harfSayisi; i++) {
            JLabel lbl = new JLabel("*");
            lbl.setName("lbl" + i);
            harfPaneli.add(lbl);
        }
        
        harfPaneli.revalidate();
        harfPaneli.repaint();
        
        yanlisTahmin = 0;
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Hata: " + e.getMessage());
    }
    
    if (timer != null) {
    timer.stop();
    }
    sure = 0;
    jLabel3.setText("Süre: 0");
    
    timer = new Timer(1000, e -> {
            sure++;
            jLabel3.setText("Süre: " + sure);
        });
        timer.start();
        
        skorlariYukle();
        loglariYukle();
}
    
    private void resimGoster() {
    String yol = resimlerDosyaAdi + resimIndex + ".jpg";
    ImageIcon icon = new ImageIcon(yol);
    Image img = icon.getImage();
    Image scaled = img.getScaledInstance(125, 125, Image.SCALE_SMOOTH);
    jLabel4.setIcon(new ImageIcon(scaled));
    jLabel4.setText("");
    resimIndex++;
}
    
    private void oyunuKaydet(String sonuc) {
    try {
        String zaman = new SimpleDateFormat("dd.MM.yyyy HH:mm:ss").format(new Date());
        String satir = zaman + " - Süre: " + sure + " saniye - Sonuç: " + sonuc + "\n";
        
        FileWriter yaz = new FileWriter(oyunlarDosyaAdi, true);
        yaz.write(satir);
        yaz.close();
        
        skorlariYukle();
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Kayıt hatası: " + e.getMessage());
    }
}
    
    private void skorlariYukle() {
    try {
         List<String> liste = Files.readAllLines(new File(oyunlarDosyaAdi).toPath(), Charset.defaultCharset());
        
        String[] sutunlar = {"Tarih", "Süre", "Sonuç"};
        DefaultTableModel model = new DefaultTableModel(null, sutunlar);
        
        for (String satir : liste) {
            if (!satir.isEmpty()) {
                String[] parcalar = satir.split(" - ");
                if (parcalar.length >= 3) {
                    model.addRow(new Object[]{parcalar[0], parcalar[1], parcalar[2]});
                }
            }
        }
        
        jTable1.setModel(model);
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Hata: " + e.getMessage());
    }
}
    
    public void loglariYukle() {
    try {
        List<String> liste = Files.readAllLines(new File(logDosyaAdi).toPath(), Charset.defaultCharset());
        
        String[] sutunlar = {"Tarih", "İşlem"};
        DefaultTableModel model = new DefaultTableModel(null, sutunlar);
        
        for (String satir : liste) {
            if (!satir.isEmpty()) {
                String[] parcalar = satir.split(" - ");
                if (parcalar.length >= 2) {
                    model.addRow(new Object[]{parcalar[1], parcalar[0]});
                }
            }
        }
        
        jTable2.setModel(model);
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Hata: " + e.getMessage());
    }
}
       
